# ---------------------------------------------------------------- BCM users / groups / grabimage


def test_cmsh_user_group_profile_and_ldap_lookup():
    s = sh()
    s.run('cmsh -c "user; add maria; set id 2010; set password pw; set profile readonly; commit"')
    s.run('cmsh -c "group; add mlteam; append members maria; commit"')
    b = s.ctx.state.bcm
    assert b.users["maria"].profile == "readonly" and "maria" in b.groups["mlteam"].members
    assert "Error: profile 'superuser' does not exist" in s.run('cmsh -c "user; use maria; set profile superuser"')
    out = s.run("ssh dgx-02 id maria")
    assert out.startswith("uid=2010(maria) gid=2010(maria)") and "(mlteam)" in out


def test_grabimage_dry_run_excludes_and_wet_run():
    s = sh()
    st = s.ctx.state
    d1 = st.nodes["dgx-01"]
    d1.files["/etc/foo.conf"] = "x=1\n"
    d1.files["/tmp/junk"] = "junk\n"
    s.run('cmsh -c "device; grabimage dgx-01"')
    log = s.run('cmsh -c "device; synclog dgx-01"')
    assert "etc/foo.conf" in log and "tmp/junk" not in log
    assert "/cm/images/dgx-os-6.2-h100-image/etc/foo.conf" not in st.nodes["bcm-head"].files
    s.run('cmsh -c "device; grabimage -w dgx-01"')
    assert st.nodes["bcm-head"].files["/cm/images/dgx-os-6.2-h100-image/etc/foo.conf"] == "x=1\n"
    s.run('cmsh -c "device; imageupdate -w -n dgx-02"')
    assert st.nodes["dgx-02"].files["/etc/foo.conf"] == "x=1\n"
