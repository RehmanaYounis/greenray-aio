"""Tests for the storage, CPU/NUMA, munge, fair-share and BCM user/fsmounts/grabimage emulation."""

from greenray.core.shell import Shell
from greenray.core.state import make_cluster


def sh():
    return Shell(make_cluster())


# ---------------------------------------------------------------- storage


def test_default_nodes_mount_home_and_cm_shared():
    s = sh()
    out = s.run("ssh dgx-01 df -h")
    assert "master:/home" in out and "/cm/shared" in out and "/raid" in out
    assert "master:/home on /home type nfs4" in s.run("ssh dgx-01 mount")
    assert "/home      10.141.0.0/16" in s.run("showmount -e master")


def test_nfs_mount_copies_server_files_and_rejects_unknown_exports():
    s = sh()
    st = s.ctx.state
    st.nodes["bcm-head"].files["/home/alice/x.txt"] = "hello\n"
    st.nodes["dgx-02"].mounts = [{"source": "/dev/nvme0n1p2", "target": "/", "fstype": "ext4", "options": "rw"}]
    assert "access denied by server" in s.run("ssh dgx-02 mount -t nfs master:/data /data")
    s.run("ssh dgx-02 mount -t nfs master:/home /home")
    assert s.run("ssh dgx-02 cat /home/alice/x.txt") == "hello"
    s.run("ssh dgx-02 umount /home")
    assert "No such file" in s.run("ssh dgx-02 cat /home/alice/x.txt")


def test_cmsh_fsmounts_commit_mounts_on_running_nodes():
    s = sh()
    st = s.ctx.state
    for n in ("dgx-01", "dgx-02", "dgx-03", "dgx-04"):
        st.nodes[n].mounts = [{"source": "/dev/nvme0n1p2", "target": "/", "fstype": "ext4", "options": "rw"}]
    s.run('cmsh -c "category; use dgx-h100; fsmounts; remove /home; commit"')
    assert not any(m.target == "/home" for m in st.nodes["dgx-01"].mounts)
    s.run('cmsh -c "category; use dgx-h100; fsmounts; add /home; set device master:/home; commit"')
    assert any(m.target == "/home" and m.source == "master:/home" for m in st.nodes["dgx-03"].mounts)
    assert "AUTOGENERATED SECTION" in st.nodes["dgx-03"].files["/etc/fstab"]
    assert "master:/home" in s.run('cmsh -c "category; use dgx-h100; fsmounts; list"')


def test_scp_and_checksums():
    s = sh()
    s.ctx.state.nodes["bcm-head"].files["/etc/munge/munge.key"] = "k1"
    s.run("scp /etc/munge/munge.key dgx-04:/etc/munge/")
    assert s.ctx.state.nodes["dgx-04"].files["/etc/munge/munge.key"] == "k1"
    assert s.run("md5sum /etc/munge/munge.key").split()[0] == s.run("ssh dgx-04 md5sum /etc/munge/munge.key").split()[0]


