"""Shared storage: NFS exports and mounts, plus small file-transfer helpers.

Commands: mount, umount, df, findmnt, showmount, exportfs, scp, md5sum, sha256sum.

State this module adds lazily (scenario setups may set them directly):

  nodes[h].mounts         [{source, target, fstype, options}] currently mounted filesystems.
                          Missing = the healthy default: local disks, and on compute nodes
                          master:/home and master:/cm/shared over NFS.
  nodes[h].mount_files    {target: [paths copied from the server when it was mounted]}
  nodes[h].exports_active [{path, clients}] what nfsd is serving (re-read by `exportfs -ra`).
                          Missing = parsed from /etc/exports (or the BCM default exports).

Mounting an NFS export copies the server's files under it onto the client, so
`ls`/`cat` on the client see them. Writes on the client are not sent back.
BCM ``fsmounts`` (cmsh category/device mode) end up in an autogenerated section of
/etc/fstab and are mounted by ``apply_fsmounts``.
"""

from __future__ import annotations

import contextlib
import hashlib
import ipaddress

from ..core.errors import CommandError
from ..core.state import HEAD
from . import HOOKS_REBOOT, HOOKS_SERVICE, command

FSTAB = "/etc/fstab"
EXPORTS = "/etc/exports"
BCM_BEGIN = "# BEGIN AUTOGENERATED SECTION -- DO NOT REMOVE"
BCM_END = "# END AUTOGENERATED SECTION   -- DO NOT REMOVE"
BCM_NOTE = "# This section of this file was automatically generated by cmd. Do not edit manually!"
DEFAULT_EXPORTS = (
    "# /etc/exports - managed by Base Command Manager (cmd)\n"
    "/cm/shared 10.141.0.0/16(rw,no_root_squash,async,no_subtree_check)\n"
    "/home 10.141.0.0/16(rw,no_root_squash,async,no_subtree_check)\n"
)
NFS_OPTS = "rsize=32768,wsize=32768,hard,async"
DEFAULT_FSMOUNTS = [
    {"mountpoint": "/cm/shared", "device": "master:/cm/shared", "filesystem": "nfs", "mountoptions": NFS_OPTS},
    {"mountpoint": "/home", "device": "master:/home", "filesystem": "nfs", "mountoptions": NFS_OPTS},
]
# (size, used) in GiB for df
SIZES = {
    "/": (1787, 61),
    "/boot/efi": (0.5, 0.01),
    "/raid": (27940, 4120),
    "/dev/shm": (1007, 0),
    "/home": (19800, 7340),
    "/cm/shared": (1800, 412),
}


# ---------------------------------------------------------------- model helpers


def _local_mounts(node) -> list[dict]:
    if node.get("role") == "head":
        return [
            {"source": "/dev/sda2", "target": "/", "fstype": "xfs", "options": "rw,relatime"},
            {"source": "/dev/sda1", "target": "/boot/efi", "fstype": "vfat", "options": "rw,relatime"},
            {"source": "tmpfs", "target": "/dev/shm", "fstype": "tmpfs", "options": "rw,nosuid,nodev"},
        ]
    return [
        {"source": "/dev/nvme0n1p2", "target": "/", "fstype": "ext4", "options": "rw,relatime"},
        {"source": "/dev/nvme0n1p1", "target": "/boot/efi", "fstype": "vfat", "options": "rw,relatime"},
        {"source": "/dev/md1", "target": "/raid", "fstype": "ext4", "options": "rw,relatime"},
        {"source": "tmpfs", "target": "/dev/shm", "fstype": "tmpfs", "options": "rw,nosuid,nodev"},
    ]


def _resolve(state, host: str):
    """'master', a hostname or an IP -> node name (or None)."""
    if host in ("master", "localhost-master", "head"):
        return HEAD
    if host in state.nodes:
        return host
    for name, node in state.nodes.items():
        if node.get("ip") == host:
            return name
    return None


def mounts(state, host) -> list:
    node = state.nodes[host]
    if "mounts" not in node:
        ms = _local_mounts(node)
        if node.get("role") != "head":
            ms += [
                {"source": "master:/cm/shared", "target": "/cm/shared", "fstype": "nfs4", "options": "rw," + NFS_OPTS},
                {"source": "master:/home", "target": "/home", "fstype": "nfs4", "options": "rw," + NFS_OPTS},
            ]
        node.mounts = ms
    node.setdefault("mount_files", {})
    return node.mounts


def _parse_exports(text: str) -> list[dict]:
    out = []
    for raw in (text or "").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        clients = []
        for c in parts[1:] or ["*"]:
            net, _, opts = c.partition("(")
            clients.append({"net": net or "*", "options": opts.rstrip(")")})
        out.append({"path": parts[0].rstrip("/") or "/", "clients": clients})
    return out


def exports(state, host) -> list:
    node = state.nodes[host]
    if "exports_active" not in node:
        text = node.files.get(EXPORTS)
        if text is None and host == HEAD:
            text = DEFAULT_EXPORTS
        node.exports_active = _parse_exports(text or "")
    return node.exports_active


def _client_allowed(client_ip: str, net: str) -> bool:
    if net == "*":
        return True
    try:
        return ipaddress.ip_address(client_ip) in ipaddress.ip_network(net, strict=False)
    except ValueError:
        return False


def _export_for(state, server, path, client_ip):
    for ex in exports(state, server):
        p = ex.path
        if path == p or path.startswith(p.rstrip("/") + "/"):
            for c in ex.clients:
                if _client_allowed(client_ip, c.net):
                    return ex
    return None


def _norm(path: str) -> str:
    return path.rstrip("/") or "/"


def _is_under(path: str, root: str) -> bool:
    root = _norm(root)
    return root == "/" or path == root or path.startswith(root + "/")


def nfs_mount(state, client: str, source: str, target: str, options: str = "", fstype: str = "nfs") -> str:
    """Mount ``server:/path`` on ``client``. Raises CommandError like mount.nfs does."""
    target = _norm(target)
    if ":" not in source:
        raise CommandError(f"mount.nfs: remote share not in 'host:dir' format: {source}", 32)
    server_name, path = source.split(":", 1)
    path = _norm(path)
    current = mounts(state, client)
    for m in current:
        if m.target == target:
            if m.source == source:
                raise CommandError(f"mount.nfs: {source} is already mounted on {target}", 32)
            raise CommandError(f"mount: {target}: mount point is busy ({m.source} is mounted there).", 32)
    server = _resolve(state, server_name)
    if server is None:
        raise CommandError(f"mount.nfs: Failed to resolve server {server_name}: Name or service not known", 32)
    snode = state.nodes[server]
    if not snode.get("up", True) or snode.get("power", "on") != "on":
        raise CommandError("mount.nfs: Connection timed out", 32)
    if snode.services.get("nfs-server", "inactive") != "active":
        raise CommandError("mount.nfs: Connection refused", 32)
    client_ip = state.nodes[client].get("ip", "")
    if _export_for(state, server, path, client_ip) is None:
        raise CommandError(f"mount.nfs: access denied by server while mounting {source}", 32)
    node = state.nodes[client]
    copied = []
    for p, content in list(snode.files.items()):
        if _is_under(p, path):
            rel = p[len(path) :] if path != "/" else p
            dst = target + rel if target != "/" else rel
            node.files[dst] = content
            copied.append(dst)
    node.mount_files[target] = copied
    fs = "nfs4" if fstype in ("nfs", "nfs4") else fstype
    current.append({"source": source, "target": target, "fstype": fs, "options": "rw," + (options or NFS_OPTS)})
    return ""


def unmount(state, host: str, target: str) -> None:
    target = _norm(target)
    current = mounts(state, host)
    m = next((m for m in current if m.target == target or m.source == target), None)
    if m is None:
        raise CommandError(f"umount: {target}: not mounted.", 32)
    if m.target == "/":
        raise CommandError("umount: /: target is busy.", 32)
    node = state.nodes[host]
    for p in node.mount_files.pop(m.target, []):
        node.files.pop(p, None)
    current.remove(m)


def path_available(state, host: str, path: str) -> bool:
    """False when ``path`` lives on an NFS export that ``host`` has not mounted."""
    if not path or host not in state.nodes or host == HEAD:
        return True
    roots = [ex.path for ex in exports(state, HEAD)] if HEAD in state.nodes else []
    if not any(_is_under(path, r) for r in roots if r != "/"):
        return True
    return any(_is_under(path, m.target) and m.target != "/" for m in mounts(state, host))


def _fstab_entries(text: str) -> list[dict]:
    out = []
    for raw in (text or "").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        f = line.split()
        if len(f) < 3:
            continue
        out.append(
            {"source": f[0], "target": _norm(f[1]), "fstype": f[2], "options": f[3] if len(f) > 3 else "defaults"}
        )
    return out


def _mount_entry(state, host, e) -> str:
    if e["fstype"] in ("nfs", "nfs4"):
        return nfs_mount(state, host, e["source"], e["target"], e["options"], e["fstype"])
    if e["target"] in ("/", "/boot/efi", "/raid", "/dev/shm", "none", "swap"):
        return ""
    raise CommandError(f"mount: {e['target']}: special device {e['source']} does not exist.", 32)


# ---------------------------------------------------------------- BCM fsmounts


def fsmount_lines(entries) -> list[str]:
    return [
        f"{e.get('device', ''):<24} {e.get('mountpoint', ''):<16} {e.get('filesystem', 'nfs'):<6} "
        f"{e.get('mountoptions') or 'defaults'} 0 0"
        for e in entries
    ]


def apply_fsmounts(state, host, entries) -> list[str]:
    """What CMDaemon does on a node when its fsmounts change: rewrite the
    autogenerated fstab section, unmount entries that went away and mount new ones."""
    node = state.nodes.get(host)
    if node is None or not node.get("up", True):
        return []
    msgs = []
    text = node.files.get(FSTAB, "")
    lines = text.splitlines()
    old_auto = []
    if BCM_BEGIN in lines and BCM_END in lines:
        b, e = lines.index(BCM_BEGIN), lines.index(BCM_END)
        old_auto = _fstab_entries("\n".join(lines[b + 1 : e]))
        head = [ln for ln in lines[:b] if ln != BCM_NOTE]
        lines = head + lines[e + 1 :]
    section = [BCM_NOTE, BCM_BEGIN, *fsmount_lines(entries), BCM_END]
    node.files[FSTAB] = "\n".join([*lines, *section]) + "\n"
    want = {_norm(e.get("mountpoint", "")): e for e in entries}
    for m in list(mounts(state, host)):
        if m.target in {o["target"] for o in old_auto} or m.target in want:
            e = want.get(m.target)
            if e is None or e.get("device") != m.source:
                unmount(state, host, m.target)
    have = {m.target for m in mounts(state, host)}
    for mp, e in want.items():
        if mp in have:
            continue
        try:
            nfs_mount(state, host, e.get("device", ""), mp, e.get("mountoptions") or "", e.get("filesystem") or "nfs")
        except CommandError as err:
            msgs.append(f"{host}: {str(err)}")
    return msgs


# ---------------------------------------------------------------- commands


def _fmt_mount(m) -> str:
    return f"{m.source} on {m.target} type {m.fstype} ({m.options})"


@command("mount", help="mount | mount -a | mount -t nfs [-o opts] server:/path /mnt | mount /mnt (from fstab)")
def mount_cmd(ctx, args):
    state, host = ctx.state, ctx.host
    fstype, opts, pos, all_ = None, "", [], False
    it = iter(args)
    for a in it:
        if a == "-t":
            fstype = next(it, None)
        elif a == "-o":
            opts = next(it, "")
        elif a in ("-a", "--all"):
            all_ = True
        elif a.startswith("-"):
            continue
        else:
            pos.append(a)
    if not pos and not all_:
        cur = mounts(state, host)
        rows = [m for m in cur if not fstype or m.fstype.startswith(fstype)]
        return "\n".join(_fmt_mount(m) for m in rows) + ("\n" if rows else "")
    fstab = _fstab_entries(ctx.node.files.get(FSTAB, ""))
    if all_:
        errs = []
        have = {m.target for m in mounts(state, host)}
        for e in fstab:
            if "noauto" in e["options"] or e["target"] in have:
                continue
            try:
                _mount_entry(state, host, e)
            except CommandError as err:
                errs.append(str(err))
        if errs:
            raise CommandError("\n".join(errs), 32)
        return ""
    if len(pos) == 1:
        e = next((e for e in fstab if e["target"] == _norm(pos[0]) or e["source"] == pos[0]), None)
        if e is None:
            raise CommandError(f"mount: {pos[0]}: can't find in /etc/fstab.", 1)
        _mount_entry(state, host, e)
        return ""
    src, tgt = pos[0], pos[1]
    if fstype in (None, "nfs", "nfs4") and ":" in src:
        return nfs_mount(state, host, src, tgt, opts, fstype or "nfs")
    raise CommandError(f"mount: {tgt}: special device {src} does not exist.", 32)


@command("umount", help="umount /mnt — unmount a filesystem")
def umount_cmd(ctx, args):
    targets = [a for a in args if not a.startswith("-")]
    if not targets:
        raise CommandError("umount: bad usage\nTry 'umount --help' for more information.", 1)
    for t in targets:
        unmount(ctx.state, ctx.host, t)
    return ""


def _human(gib: float) -> str:
    if gib >= 1024:
        return f"{gib / 1024:.1f}T"
    if gib >= 1:
        return f"{gib:.0f}G"
    return f"{gib * 1024:.0f}M"


@command("df", help="df [-h] [-T] [path...] — filesystem usage (shows which filesystem a path is on)")
def df_cmd(ctx, args):
    human = any(a in ("-h", "--human-readable") or (a.startswith("-") and "h" in a[1:]) for a in args)
    show_t = any(
        a in ("-T", "--print-type") or (a.startswith("-") and not a.startswith("--") and "T" in a) for a in args
    )
    paths = [a for a in args if not a.startswith("-")]
    cur = mounts(ctx.state, ctx.host)
    if paths:
        rows = []
        for p in paths:
            best = max((m for m in cur if _is_under(_norm(p), m.target)), key=lambda m: len(m.target), default=None)
            if best is None:
                raise CommandError(f"df: {p}: No such file or directory", 1)
            if best not in rows:
                rows.append(best)
    else:
        rows = list(cur)
    hdr = ["Filesystem", "Type", "Size" if human else "1K-blocks", "Used", "Avail", "Use%", "Mounted on"]
    out = []
    for m in rows:
        size, used = SIZES.get(m.target, (100, 1))
        if human:
            vals = [_human(size), _human(used), _human(size - used)]
        else:
            vals = [str(int(size * 1048576)), str(int(used * 1048576)), str(int((size - used) * 1048576))]
        pct = f"{round(100 * used / size) if size else 0}%"
        out.append([m.source, m.fstype, *vals, pct, m.target])
    if not show_t:
        hdr.pop(1)
        out = [r[:1] + r[2:] for r in out]
    widths = [max(len(str(r[i])) for r in [hdr, *out]) for i in range(len(hdr))]
    lines = []
    for r in [hdr, *out]:
        cells = [f"{c:<{widths[0]}}" if i == 0 else f"{c:>{widths[i]}}" for i, c in enumerate(r[:-1])]
        lines.append(" ".join(cells) + " " + r[-1])
    return "\n".join(lines) + "\n"


@command("findmnt", help="findmnt [target] [-t nfs,nfs4] [--fstab] — show mounted filesystems")
def findmnt_cmd(ctx, args):
    types = None
    use_fstab = "--fstab" in args or "-s" in args
    pos, it = [], iter(args)
    for a in it:
        if a in ("-t", "--types"):
            types = next(it, "").split(",")
        elif a.startswith("-"):
            continue
        else:
            pos.append(a)
    if use_fstab:
        rows = [
            {"target": e["target"], "source": e["source"], "fstype": e["fstype"], "options": e["options"]}
            for e in _fstab_entries(ctx.node.files.get(FSTAB, ""))
        ]
    else:
        rows = [dict(m) for m in mounts(ctx.state, ctx.host)]
    if types:
        rows = [r for r in rows if r["fstype"] in types or (r["fstype"].startswith("nfs") and "nfs" in types)]
    if pos:
        rows = [r for r in rows if r["target"] == _norm(pos[0]) or r["source"] == pos[0]]
        if not rows:
            raise CommandError("", 1)
    if not rows:
        raise CommandError("", 1)
    w = [max(len("TARGET"), *(len(r["target"]) for r in rows)), max(len("SOURCE"), *(len(r["source"]) for r in rows))]
    w.append(max(len("FSTYPE"), *(len(r["fstype"]) for r in rows)))
    out = [f"{'TARGET':<{w[0]}} {'SOURCE':<{w[1]}} {'FSTYPE':<{w[2]}} OPTIONS"]
    out += [f"{r['target']:<{w[0]}} {r['source']:<{w[1]}} {r['fstype']:<{w[2]}} {r['options']}" for r in rows]
    return "\n".join(out) + "\n"


@command("showmount", help="showmount -e <server> — list what an NFS server exports")
def showmount_cmd(ctx, args):
    pos = [a for a in args if not a.startswith("-")]
    server_name = pos[0] if pos else ctx.host
    server = _resolve(ctx.state, server_name)
    if server is None:
        raise CommandError("clnt_create: RPC: Unknown host", 1)
    snode = ctx.state.nodes[server]
    if not snode.get("up", True):
        raise CommandError("clnt_create: RPC: Port mapper failure - Unable to receive: errno 113 (No route to host)", 1)
    if snode.services.get("nfs-server", "inactive") != "active":
        raise CommandError("clnt_create: RPC: Program not registered", 1)
    exs = exports(ctx.state, server)
    w = max([len(e.path) for e in exs] + [1])
    out = [f"Export list for {server_name}:"]
    out += [f"{e.path:<{w}} {','.join(c.net for c in e.clients)}" for e in exs]
    return "\n".join(out) + "\n"


@command("exportfs", help="exportfs -v | -ra | -s — show or re-read NFS exports (/etc/exports)")
def exportfs_cmd(ctx, args):
    node = ctx.node
    flags = "".join(a[1:] for a in args if a.startswith("-") and not a.startswith("--"))
    if "r" in flags or "a" in flags:
        if "nfs-server" not in node.services:
            raise CommandError("exportfs: nfs-server is not installed on this host", 1)
        text = node.files.get(EXPORTS)
        if text is None and ctx.host == HEAD:
            text = DEFAULT_EXPORTS
        node.exports_active = _parse_exports(text or "")
        if "v" not in flags:
            return ""
    exs = exports(ctx.state, ctx.host) if "nfs-server" in node.services else []
    out = []
    for e in exs:
        for c in e.clients:
            opts = [o for o in (c.options or "ro").split(",") if o]
            if "v" in flags:
                merged = [
                    "sync",
                    "wdelay",
                    "hide",
                    "no_subtree_check",
                    "sec=sys",
                    "ro",
                    "secure",
                    "root_squash",
                    "no_all_squash",
                ]
                pairs = {"async": "sync", "rw": "ro", "no_root_squash": "root_squash", "insecure": "secure"}
                for o in opts:
                    if o in pairs and pairs[o] in merged:
                        merged[merged.index(pairs[o])] = o
                    elif o not in merged:
                        merged.append(o)
                out.append(f"{e.path:<16}\t{c.net}({','.join(merged)})")
            else:
                out.append(f"{e.path:<16}\t{c.net}({','.join(opts)})" if "s" in flags else f"{e.path:<16}\t{c.net}")
    return "\n".join(out) + ("\n" if out else "")


# ---------------------------------------------------------------- file transfer / checksums


def _split_remote(spec):
    if ":" in spec and not spec.startswith("/"):
        host, path = spec.split(":", 1)
        return host.split("@")[-1], path
    return None, spec


@command("scp", help="scp [-p] src dst — copy a file between nodes (host:/path)")
def scp_cmd(ctx, args):
    pos = [a for a in args if not a.startswith("-")]
    if len(pos) < 2:
        raise CommandError("usage: scp [-p] [[user@]host1:]file1 ... [[user@]host2:]file2", 1)
    *srcs, dst = pos
    dhost, dpath = _split_remote(dst)
    dhost = _resolve(ctx.state, dhost) if dhost else ctx.host
    if dhost is None:
        raise CommandError(f"ssh: Could not resolve hostname {dst.split(':')[0]}: Name or service not known", 255)
    dnode = ctx.state.nodes[dhost]
    if not dnode.get("up", True):
        raise CommandError(f"ssh: connect to host {dhost} port 22: No route to host", 255)
    out = []
    for src in srcs:
        shost, spath = _split_remote(src)
        shost = _resolve(ctx.state, shost) if shost else ctx.host
        if shost is None or not ctx.state.nodes[shost].get("up", True):
            raise CommandError(f"ssh: connect to host {src.split(':')[0]} port 22: No route to host", 255)
        files = ctx.state.nodes[shost].files
        if spath not in files:
            raise CommandError(f"scp: {spath}: No such file or directory", 1)
        target = dpath or "/root"
        base = spath.rsplit("/", 1)[-1]
        if target.endswith("/") or any(f.startswith(target.rstrip("/") + "/") for f in dnode.files):
            target = target.rstrip("/") + "/" + base
        dnode.files[target] = files[spath]
        size = len(files[spath])
        out.append(f"{base:<40} 100% {size:>5}     1.1MB/s   00:00")
    return "\n".join(out) + "\n"


def _sum(ctx, args, algo):
    files = [a for a in args if not a.startswith("-")]
    if not files:
        return f"{getattr(hashlib, algo)(ctx.stdin.encode()).hexdigest()}  -\n"
    out = []
    for f in files:
        if f not in ctx.node.files:
            raise CommandError(f"{algo}sum: {f}: No such file or directory", 1)
        out.append(f"{getattr(hashlib, algo)(ctx.node.files[f].encode()).hexdigest()}  {f}")
    return "\n".join(out) + "\n"


@command("md5sum", help="md5sum FILE... — compare files across nodes (e.g. /etc/munge/munge.key)")
def md5sum_cmd(ctx, args):
    return _sum(ctx, args, "md5")


@command("sha256sum", help="sha256sum FILE...")
def sha256sum_cmd(ctx, args):
    return _sum(ctx, args, "sha256")


# ---------------------------------------------------------------- hooks


def _reboot_hook(ctx, node):
    """After a reboot only local disks and what /etc/fstab mounts at boot are present."""
    state = ctx.state
    name = node.get("hostname") or ctx.host
    if name not in state.nodes or "mounts" not in state.nodes[name]:
        return  # healthy default (BCM mounts /home and /cm/shared at boot)
    n = state.nodes[name]
    for target in list(n.get("mount_files", {})):
        for p in n.mount_files.pop(target, []):
            n.files.pop(p, None)
    n.mounts = _local_mounts(n)
    for e in _fstab_entries(n.files.get(FSTAB, "")):
        if "noauto" in e["options"]:
            continue
        with contextlib.suppress(CommandError):
            _mount_entry(state, name, e)


def _service_hook(ctx, name, action):
    if name == "nfs-server" and action in ("start", "restart", "reload"):
        ctx.node.pop("exports_active", None)


HOOKS_REBOOT.append(_reboot_hook)
